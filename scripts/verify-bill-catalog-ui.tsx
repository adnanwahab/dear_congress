import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { fireEvent } from '@testing-library/dom';
const dom = new Window({ url: 'http://localhost/bills' });
for (const key of ['window', 'document', 'navigator', 'localStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const { default: BillCatalog } = await import('../src/client/BillCatalog');
const container = document.createElement('div'); document.body.append(container);
const root = createRoot(container);
let writes = 0;
globalThis.fetch = async () => { writes++; throw new Error('Catalog must not fetch or submit'); };
await act(async () => root.render(<BillCatalog />));
assert.equal(container.querySelectorAll('article').length, 100);
assert.equal(container.querySelectorAll('.bill-chips [aria-pressed]').length, 11);
for (const card of container.querySelectorAll('article')) assert(card.textContent!.includes('Legal authority: unverified'));
for (const card of container.querySelectorAll('article')) assert.match(card.textContent!, /Publish gate: blocked/);
const input = container.querySelector('input')!;
input.focus();
await act(async () => { fireEvent.input(input, { target: { value: 'HFL-051' } }); });
assert.equal(document.activeElement, input);
assert.equal(container.querySelectorAll('article').length, 1);
assert.equal(new URLSearchParams(window.location.search).get('q'), 'HFL-051');
const link = container.querySelector('article a')!;
assert.match(link.getAttribute('href')!, /^\/bills\/HFL-051\?q=HFL-051$/);
await act(async () => { (container.querySelector('.bill-chips [aria-pressed="false"]') as HTMLButtonElement).click(); });
assert.match(container.textContent!, /No draft concepts match/);
await act(async () => { const reset = [...container.querySelectorAll('button')].find(b => b.textContent === 'Clear / reset')!; reset.click(); });
assert.equal(container.querySelectorAll('article').length, 100);
assert.equal(window.location.search, '');
// Restored URL drives controls and results on native history notification.
await act(async () => { window.history.replaceState(null, '', '/bills?q=HFL-051'); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
assert.equal(input.value, 'HFL-051');
assert.equal(container.querySelectorAll('article').length, 1);
await act(async () => root.unmount());
window.history.replaceState(null, '', '/bills/HFL-051');
const detailRoot = createRoot(container);
await act(async () => detailRoot.render(<BillCatalog />));
for (const text of ['Third Places for Everyone Act', 'Unknown until assessed', 'Statutory text', 'Proposed funding scenarios', 'Con arguments', 'Evidence plan', 'Review before participation', 'Immutable catalog revision', 'Legal-authority checklist', 'Legal review status: unverified', 'Unassigned / not reviewed']) assert(container.textContent!.includes(text), text);
for (const text of ['Human editorial review gate', 'Human review incomplete', 'publication unavailable']) assert(container.textContent!.includes(text), text);
assert.equal(container.querySelectorAll('input,form').length, 1);
const questionSearch = container.querySelector('#policy-question-search') as HTMLInputElement;
questionSearch.focus();
await act(async () => fireEvent.input(questionSearch, { target: { value: 'cost' } }));
assert.equal(document.activeElement, questionSearch);
await act(async () => (container.querySelector('[aria-label="Policy questions"] button') as HTMLButtonElement).click());
assert.equal(new URLSearchParams(window.location.search).get('question'), 'cost');
assert.match(document.activeElement!.textContent!, /What could it cost/);
assert.match(container.textContent!, /Evidence freshness: not checked/);
assert.equal(container.querySelector('a[href="#catalog-metrics"]')?.textContent?.includes('HFL-051'), true);
for (const question of ['risk', 'cost']) {
  await act(async () => { window.history.replaceState(null, '', `/bills/HFL-051?q=parks&question=${question}`); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
  assert.equal(container.querySelector('[aria-label="Policy questions"] [aria-pressed="true"]')?.textContent?.includes(question === 'risk' ? 'wrong' : 'cost'), true);
  assert.equal(questionSearch.value, '');
}
assert.equal(writes, 0);
const nextLens = [...container.querySelectorAll('button')].find(b => b.textContent === 'Rotate next lens')!;
nextLens.focus();
await act(async () => nextLens.click());
assert.equal(document.activeElement, nextLens);
assert.equal(container.querySelector('[aria-label="Law lens"]')?.textContent?.includes('Hypothetical draft context'), true);
assert.equal(window.location.pathname, '/bills/HFL-051');
assert.equal(new URLSearchParams(window.location.search).get('lens'), '1');
await act(async () => { window.history.replaceState(null, '', '/bills/HFL-051?lens=3&prism=static'); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
assert(container.querySelector('[aria-label="Lived impact lens"]'));
assert.equal(container.querySelector('.governance-prism')?.getAttribute('data-static'), 'true');
await act(async () => { window.history.replaceState(null, '', '/bills/HFL-051?lens=0'); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
assert(container.querySelector('[aria-label="Cost lens"]'));
await act(async () => detailRoot.unmount());
await dom.happyDOM.close();
console.log('PASS catalog: 100 cards, search, category intersection, reset, history restoration, detail and zero writes');
