import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { fireEvent } from '@testing-library/dom';
const dom = new Window({ url: 'http://localhost/bills' });
for (const key of ['window', 'document', 'navigator', 'localStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const { default: BillCatalog } = await import('../src/client/BillCatalog');
const container = document.createElement('div'); document.body.append(container);
const root = createRoot(container);
let writes = 0;
globalThis.fetch = async () => { writes++; throw new Error('Catalog must not fetch or submit'); };
await act(async () => root.render(<BillCatalog />));
assert.equal(container.querySelectorAll('article').length, 100);
assert.equal(container.querySelectorAll('.bill-chips [aria-pressed]').length, 11);
const input = container.querySelector('input')!;
input.focus();
await act(async () => { fireEvent.input(input, { target: { value: 'HFL-051' } }); });
assert.equal(document.activeElement, input);
assert.equal(container.querySelectorAll('article').length, 1);
assert.equal(new URLSearchParams(window.location.search).get('q'), 'HFL-051');
const link = container.querySelector('article a')!;
assert.match(link.getAttribute('href')!, /^\/bills\/HFL-051\?q=HFL-051$/);
await act(async () => { (container.querySelector('.bill-chips [aria-pressed="false"]') as HTMLButtonElement).click(); });
assert.match(container.textContent!, /No draft concepts match/);
await act(async () => { const reset = [...container.querySelectorAll('button')].find(b => b.textContent === 'Clear / reset')!; reset.click(); });
assert.equal(container.querySelectorAll('article').length, 100);
assert.equal(window.location.search, '');
// Restored URL drives controls and results on native history notification.
await act(async () => { window.history.replaceState(null, '', '/bills?q=HFL-051'); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
assert.equal(input.value, 'HFL-051');
assert.equal(container.querySelectorAll('article').length, 1);
// Atlas shares filters and native links, with static controls in reduced motion.
const region = container.querySelector('select')!;
input.focus();
await act(async () => { fireEvent.input(input, { target: { value: '' } }); });
region.focus();
await act(async () => { fireEvent.change(region, { target: { value: 'south' } }); });
assert.equal(document.activeElement, region);
assert.equal(new URLSearchParams(window.location.search).get('region'), 'south');
assert.match(container.textContent!, /No reviewed region-specific proposal bindings/);
assert([...container.querySelectorAll('article .bill-meta')].every(n => n.textContent!.includes('federal')));
assert.match(container.querySelector('article a')!.getAttribute('href')!, /region=south/);
const scope = container.querySelectorAll('select')[1]!;
await act(async () => fireEvent.change(scope, { target: { value: 'city' } }));
assert.equal(container.querySelectorAll('article').length, 0);
assert.match(container.textContent!, /No draft concepts match/);
// Back and forward notifications restore all atlas and catalog controls together.
for (const url of ['/bills?view=atlas&region=west&scope=federal', '/bills?region=south&scope=city']) {
  await act(async () => { window.history.replaceState(null, '', url); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
  assert.equal(region.value, new URLSearchParams(window.location.search).get('region'));
  assert.equal(scope.value, new URLSearchParams(window.location.search).get('scope'));
}
const originalMatchMedia = window.matchMedia.bind(window);
window.matchMedia = ((query: string) => { const media = originalMatchMedia(query); if (query.includes('prefers-reduced-motion')) Object.defineProperty(media, 'matches', { value: true }); return media; }) as typeof window.matchMedia;
await act(async () => { window.history.replaceState(null, '', '/bills?view=atlas&region=west'); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
assert.equal(container.querySelectorAll('.atlas-overview button').length, 4);
const lowPower = [...container.querySelectorAll('button')].find(b => b.textContent === 'Use text-only regions / low power')!;
lowPower.focus();
const beforeIds = [...container.querySelectorAll('article .bill-meta')].map(n => n.textContent);
await act(async () => lowPower.click());
assert.equal(document.activeElement, lowPower);
assert.equal(container.querySelector('.atlas-overview'), null);
assert.deepEqual([...container.querySelectorAll('article .bill-meta')].map(n => n.textContent), beforeIds);
await act(async () => root.unmount());
window.history.replaceState(null, '', '/bills/HFL-051');
const detailRoot = createRoot(container);
await act(async () => detailRoot.render(<BillCatalog />));
for (const text of ['Third Places for Everyone Act', 'Unknown until assessed', 'Statutory text', 'Proposed funding scenarios', 'Con arguments', 'Evidence plan', 'Review before participation', 'Immutable catalog revision']) assert(container.textContent!.includes(text), text);
assert.equal(container.querySelectorAll('input,form').length, 0);
assert.equal(writes, 0);
await act(async () => detailRoot.unmount());
await dom.happyDOM.close();
console.log('PASS catalog: 100 cards, search, category intersection, reset, history restoration, detail and zero writes');
