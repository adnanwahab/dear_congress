/** Isolated DOM interaction check; never starts a server or contacts a service. */
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { PatchSubway } from '../src/client/PatchSubway';
import type { PublicPull } from '../src/shared/hbl-governance';
const dom=new Window({url:'http://localhost/vote/dear_congress?view=prs'});
for(const key of ['window','document','navigator'])Object.defineProperty(globalThis,key,{configurable:true,value:key==='window'?dom:(dom as any)[key]});
(globalThis as any).IS_REACT_ACT_ENVIRONMENT=true;
let requests=0;
globalThis.fetch=async()=>{requests++;throw Error('No requests allowed');};
const container=dom.document.createElement('div');dom.document.body.append(container);
const {createRoot}=await import('react-dom/client');
const root=createRoot(container as any);
const pulls:PublicPull[]=[1,2].map(number=>({number,repositoryId:123,title:`Feature ${number}`,body:'',author:'a',url:`https://github.com/adnanwahab/dear_congress/pull/${number}`,updatedAt:'',headSha:'a'.repeat(40),base:'main',draft:false,state:'open',version:`123:${number}:head:main`,firstSeenAt:0,labels:[],links:[`https://linear.app/team/issue/SHE-${number}`],tally:{yes:1,no:0,participation:1,feedback:0},eligibility:{eligible:false,state:'blocked',reason:'Pilot lock'}}));
const original=JSON.stringify(pulls);
await act(async()=>root.render(<PatchSubway pulls={pulls} repository="adnanwahab/dear_congress" loading={false} error="" stale={false} sourceStatus="current" permission="Public read access"/>));
assert.equal(container.querySelectorAll('article').length,2);
const input=container.querySelector('input')!;
input.focus();assert.equal(dom.document.activeElement,input);
await act(async()=>{Object.getOwnPropertyDescriptor(dom.HTMLInputElement.prototype,'value')!.set!.call(input,'SHE-2');input.dispatchEvent(new dom.Event('input',{bubbles:true}));input.dispatchEvent(new dom.Event('change',{bubbles:true}));});
assert.equal(container.querySelectorAll('article').length,1);
assert.match(container.querySelector('tbody')!.textContent!,/SHE-2/);
assert.doesNotMatch(container.querySelector('tbody')!.textContent!,/SHE-1/);
const link=container.querySelector('tbody a')!;
(link as any).focus();assert.equal(dom.document.activeElement,link);
assert.match(link.getAttribute('href')!,/^https:\/\/github.com\/adnanwahab\/dear_congress\/pull\/2$/);
assert.equal(requests,0);assert.equal(JSON.stringify(pulls),original);
await act(async()=>root.unmount());await dom.happyDOM.close();
console.log('PASS search synchronizes map/table, native links focus, no requests or vote mutation');
