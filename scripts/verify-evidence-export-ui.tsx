import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { EvidenceExport } from '../src/client/EvidenceExport';
import { DEMO_ITEMS } from '../src/engine/demo';
const dom = new Window({ url: 'http://localhost/draft' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => root.render(<EvidenceExport item={DEMO_ITEMS[0]!} />));
const details = container.querySelector('details')!;
assert(!details.open);
(container.querySelector('summary') as any).click(); assert(details.open);
// Native buttons expose the same activation to pointer/touch and keyboard users.
const buttons = container.querySelectorAll('button');
assert.equal(buttons[0]!.getAttribute('type'), 'button');
const original = URL.createObjectURL;
URL.createObjectURL = () => { throw new Error('Download unsupported'); };
await act(async () => (buttons[0] as any).click());
assert.match(container.querySelector('[role=status]')!.textContent!, /Download unavailable/);
const json = JSON.parse((container.querySelector('textarea') as any).value);
assert.equal(json.proposal.id, DEMO_ITEMS[0]!.id);
assert.equal(json.evidenceSummary.review, 'Unreviewed');
assert(container.querySelector('textarea')!.hasAttribute('readonly'));
(dom as any).print = () => { throw new Error('Unsupported'); };
await act(async () => (container.querySelectorAll('button')[2] as any).click());
assert.match(container.querySelector('[role=status]')!.textContent!, /Printing unavailable/);
await act(async () => (buttons[1] as any).click());
assert.match(container.querySelector('[role=status]')!.textContent!, /Packet ready/);
URL.createObjectURL = original;
await act(async () => root.unmount());
dom.happyDOM.abort();
console.log('PASS evidence export offline, download failure, copy and print fallbacks');
