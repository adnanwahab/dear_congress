import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { PublicMeetings } from '../src/client/PublicMeetings';
const dom = new Window({ url: 'http://localhost/feed' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
let resolve!: (value: any) => void;
let fail = false;
const record = { id: 'test:1', title: 'Test meeting', jurisdiction: 'Houston', topics: ['Transit'], organizer: 'Test organizer', verifiedBy: 'Test reviewer', sourceUrl: 'https://example.org/notice', checkedAt: '2020-01-01T00:00:00Z', startsAt: '2030-01-01T12:00:00Z', agenda: null };
const request = <T,>() => fail ? Promise.reject(new Error('offline')) : new Promise<T>(r => { resolve = r; });
await act(async () => root.render(<PublicMeetings request={request} jurisdiction="Houston" />));
assert.match(container.textContent!, /Loading public meeting sources/);
await act(async () => resolve({ meetings: [record, { ...record, id: 'test:2', jurisdiction: 'Texas' }] }));
assert.match(container.textContent!, /1 meetings match/);
assert.match(container.textContent!, /Agenda unavailable/);
assert.match(container.textContent!, /Source is stale/);
const topic = container.querySelector('select')! as any;
await act(async () => { topic.value = 'Transit'; topic.dispatchEvent(new dom.Event('change', { bubbles: true })); });
assert.match(container.textContent!, /1 meetings match/);
const checkbox = container.querySelector('input')! as any;
assert.equal(checkbox.checked, false, 'reminders default off');
assert.equal(container.querySelectorAll('a[download]').length, 0, 'reading never exports');
let exported: Blob | undefined;
const oldCreate = URL.createObjectURL;
URL.createObjectURL = blob => { exported = blob as Blob; return 'blob:test'; };
const oldClick = dom.HTMLAnchorElement.prototype.click;
dom.HTMLAnchorElement.prototype.click = function () {};
await act(async () => { (container.querySelector('.meeting-card button') as any).click(); });
assert(!(await exported!.text()).includes('BEGIN:VALARM'));
await act(async () => { checkbox.click(); }); assert.equal(checkbox.checked, true);
await act(async () => { (container.querySelector('.meeting-card button') as any).click(); });
assert((await exported!.text()).includes('BEGIN:VALARM'));
URL.createObjectURL = oldCreate; dom.HTMLAnchorElement.prototype.click = oldClick;
await act(async () => root.render(<PublicMeetings request={request} jurisdiction="Texas" />));
assert.match(container.textContent!, /1 meetings match/);
assert.equal((container.querySelector('input') as any).checked, false, 'opt-in is isolated per source record');
fail = true;
await act(async () => { (container.querySelector('section > button') as any).click(); });
assert.match(container.textContent!, /Public meeting sources unavailable/);
assert.equal(container.querySelectorAll('.meeting-card').length, 0);
fail = false;
await act(async () => { (container.querySelector('section > button') as any).click(); });
await act(async () => resolve({ meetings: [{ ...record, startsAt: null }] }));
await act(async () => root.render(<PublicMeetings request={request} jurisdiction="Houston" />));
assert.match(container.textContent!, /Meeting time unavailable/);
assert.equal(container.querySelectorAll('.meeting-card button').length, 0);
await act(async () => root.unmount());
console.log('PASS meetings loading, jurisdiction, stale source, missing agenda/time, consent isolation and failure retry');
