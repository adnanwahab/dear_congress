import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'https://example.test/feed?live=secret&ref=person' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { within, fireEvent } = await import('@testing-library/dom');
const { DiscussionInvitation } = await import('../src/client/DiscussionInvitation');
let shares: ShareData[] = [], copies: string[] = [];
Object.defineProperty(navigator, 'share', { configurable: true, value: async (data: ShareData) => { shares.push(data); throw new DOMException('Canceled', 'AbortError'); } });
Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text: string) => { copies.push(text); } } });
document.body.innerHTML = '<div id="root"></div>';
const root = createRoot(document.getElementById('root')!);
const q = () => within(document.body);
const render = async (id: string) => { await act(async () => root.render(<DiscussionInvitation id={id} />)); };
const click = async (name: string) => { await act(async () => fireEvent.click(q().getByRole('button', { name }))); };
await render('demo-transit');
assert.equal(q().queryByRole('textbox'), null);
await click('Compare this proposal with someone');
const text = (q().getByRole('textbox') as HTMLTextAreaElement).value;
assert.ok(text.includes('non-binding beta') && text.includes('fictional sample'));
assert.ok(text.includes('reasons for and concerns'));
assert.ok(text.includes('https://example.test/published?proposal=demo-transit'));
assert.ok(!text.includes('secret') && !text.includes('ref=') && !text.includes('Optional chosen stance'));
assert.equal(shares.length + copies.length, 0);
await click('Open device share sheet');
assert.equal(shares.length, 1); assert.equal(copies.length, 0);
assert.ok(q().getByRole('status').textContent!.includes('canceled'));
await click('Copy invitation');
assert.deepEqual(copies, [text]);
await render('demo-housing');
assert.equal(q().queryByRole('textbox'), null);
Object.defineProperty(navigator, 'share', { configurable: true, value: undefined });
await click('Compare this proposal with someone');
assert.equal(q().queryByRole('button', { name: 'Open device share sheet' }), null);
assert.ok((q().getByRole('textbox') as HTMLTextAreaElement).value.includes('demo-housing'));
Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined });
await click('Copy invitation');
assert.ok(q().getByRole('status').textContent!.includes('manually'));
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('Invitation interactions passed');
