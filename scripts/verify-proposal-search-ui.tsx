import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';

import { fireEvent } from '@testing-library/dom';
import { Dashboard } from '../src/client/Dashboard';
import WorkflowScreen from '../src/client/WorkflowScreen';
import { demoPayload } from '../src/engine/demo';
import { filterProposals } from '../src/client/ProposalSearch';
const dom = new Window({ url: 'http://localhost/feed' });
for (const key of ['window', 'document', 'navigator', 'localStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const payload = demoPayload({}, 'test');
for (const screen of ['home', 'feed'] as const) {
  const container = dom.document.createElement('div'); dom.document.body.append(container);
  const root = createRoot(container as any);
  let calls = 0;
  let resolve!: (value: typeof payload) => void;
  let fail = true;
  const request = <T,>(): Promise<T> => { calls++; return fail ? Promise.reject(new Error('offline')) : new Promise(r => { resolve = r as any; }); };
  await act(async () => { root.render(screen === 'home' ? <Dashboard request={request} /> : <WorkflowScreen stage="feed" request={request} />); });
  assert.match(container.textContent!, /Sample proposals unavailable/);
  assert(!container.textContent!.includes('Showing 0'));
  fail = false;
  await act(async () => { (container.querySelector('[role=alert] button') as any).click(); });
  assert(!container.textContent!.includes('Showing 0'));
  await act(async () => { resolve(payload); });
  const form = container.querySelector('form[role=search]')!;
  const input = form.querySelector('input')!;
  const select = form.querySelector('select')!;
  const countText = () => container.querySelector('.proposal-search [role=status]')!.textContent;
  assert.equal(countText(), `Showing ${payload.items.length} of ${payload.items.length} proposals · Sample data`);
  const baseline = calls;
  await act(async () => { fireEvent.change(select, { target: { value: payload.items[0]!.topic } }); });
  assert.equal(countText(), `Showing ${filterProposals(payload.items, '', select.value).length} of ${payload.items.length} proposals · Sample data`);
  await act(async () => { fireEvent.input(input, { target: { value: 'zzzz-no-match' } }); });
  assert.equal(input.value, 'zzzz-no-match');
  assert.match(countText()!, /Showing 0 of/);
  assert.match(container.querySelector('.proposal-search')!.textContent!, /Reset filters/);
  await act(async () => { fireEvent.submit(form); fireEvent.keyDown(input, { key: 'Escape' }); });
  assert.equal(input.value, '');
  await act(async () => { (form.querySelector('button') as any).click(); });
  assert.equal(select.value, 'All topics');
  assert.equal(dom.document.activeElement, input);
  assert.equal(calls, baseline, 'search, submit and reset must stay local');
  await act(async () => root.unmount()); container.remove();
  console.log(`PASS ${screen}: retry, counts, topic, keyboard, reset and local requests`);
}
await dom.happyDOM.close();
