import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { CitizenJury } from '../src/client/CitizenJury';
import { demoPayload } from '../src/engine/demo';
const dom = new Window({ url: 'http://localhost/votes' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
const item = demoPayload({}, 'test').items[0]!;
await act(async () => root.render(<CitizenJury item={item} />));
const button = (name: string) => [...container.querySelectorAll('button')].find(b => b.textContent === name)!;
const click = async (name: string) => { await act(async () => (button(name) as any).click()); };
await click('Open local rehearsal');
assert(button('Finish or pass turn').disabled);
for (const box of [...container.querySelectorAll('fieldset:first-of-type input[type=checkbox]')]) await act(async () => (box as any).click());
assert(!button('Finish or pass turn').disabled);
await click('Report concern and pause');
assert(button('Finish or pass turn').disabled);
await click('Facilitator: concern reviewed, keep paused');
for (let i = 0; i < 9; i++) await click('Finish or pass turn');
const textarea = container.querySelector('textarea')!;
async function edit(text: string) { await act(async () => { Object.getOwnPropertyDescriptor(dom.HTMLTextAreaElement.prototype, 'value')!.set!.call(textarea, text); textarea.dispatchEvent(new dom.Event('input', { bubbles: true })); }); }
await edit('A summary with dissent.');
for (const box of [...container.querySelectorAll('fieldset:last-of-type input')]) await act(async () => (box as any).click());
assert(container.querySelector('[aria-label="Consented local summary"]'));
await edit('Changed summary');
assert(!container.querySelector('[aria-label="Consented local summary"]'));
await click('Delete room, notes and consent / withdraw');
assert(!container.querySelector('textarea'));
await click('Open local rehearsal');
assert.equal(container.querySelector('textarea')!.value, '');
assert(button('Finish or pass turn').disabled);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS jury: consent, moderation pause, equal turns, exact-summary invalidation, deletion');
