import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
const dom = new Window({ url: 'http://localhost/proposals/test' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const { ProposalWorkshop } = await import('../src/client/ProposalWorkshop');
globalThis.fetch = async () => { throw Error('Workshop must not fetch'); };
const container = document.createElement('div'); document.body.append(container);
const root = createRoot(container);
await act(async () => root.render(<ProposalWorkshop source={{ id: 'one', title: '<script>source</script>', problem: 'Late buses', proposedChange: 'Pilot', publishedAt: '2026-11-14' }} />));
const button = (text: string) => [...container.querySelectorAll('button')].find(b => b.textContent === text)!;
assert.equal(button('Prepare read-only summary').disabled, true);
assert.equal(button('Public collaboration unavailable').disabled, true);
assert.equal(container.querySelectorAll('textarea').length, 6);
for (const field of container.querySelectorAll('textarea,input')) assert(container.querySelector(`label[for="${field.id}"]`) || field.closest('label'));
await act(async () => (container.querySelector('input[type=checkbox]') as HTMLInputElement).click());
await act(async () => button('Prepare read-only summary').click());
const summary = container.querySelector('textarea[readonly]') as HTMLTextAreaElement;
assert.match(summary.value, /citizen:one/); assert.match(summary.value, /Late buses/);
assert.equal(container.querySelectorAll('script').length, 0);
await act(async () => button('Opt out and clear notes').click());
assert.equal(container.querySelector('textarea[readonly]'), null);
assert.equal(button('Export attributed draft').disabled, true);
assert.match(container.querySelector('[role=status]')!.textContent!, /Opted out/);
await act(async () => root.unmount());
console.log('PASS workshop consent and summary');
