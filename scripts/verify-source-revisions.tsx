import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { SourceRevisionAlert } from '../src/client/SourceRevisionAlert';
import { SYNTHETIC_METRICS } from '../src/shared/policy-measurements';
const dom = new Window({ url: 'http://localhost/outcomes' });
Object.defineProperty(globalThis, 'window', { configurable: true, value: dom });
Object.defineProperty(globalThis, 'document', { configurable: true, value: dom.document });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
const measurement = SYNTHETIC_METRICS[0]!.history[1]!;
await act(async () => {
  root.render(<SourceRevisionAlert sourceId="wait" measurement={measurement} />);
});
await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); });
assert.match(container.textContent!, /No source monitoring/);
const button = container.querySelector('button')!;
assert.equal(button.disabled, false);
button.focus();
assert.equal(dom.document.activeElement, button);
await act(async () => { button.click(); });
assert.match(container.textContent!, /Reviewer acknowledgment required/);
assert.match(container.textContent!, /Before: 15 → After: 16/);
assert.match(container.textContent!, /Published claim pinned to wait-2025 · 15 minutes/);
const record = JSON.parse(container.querySelector('details pre')!.textContent!);
assert.equal(record.snapshots.length, 2);
assert.deepEqual(record.reviewLog, []);
assert.match(record.snapshots[0].hash, /^sha256:/);
await act(async () => { button.click(); });
assert.equal(JSON.parse(container.querySelector('details pre')!.textContent!).snapshots.length, 1);
await act(async () => { root.unmount(); });
await dom.happyDOM.close();
console.log('PASS local correction, focus, retained claim and copyable export');
