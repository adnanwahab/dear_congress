import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'https://example.test/votes?journal=SECRET&stance=1&live=PRIVATE#receipt' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { within, fireEvent } = await import('@testing-library/dom');
const { ShareSampleLink, sampleShareData } = await import('../src/client/ShareSampleLink');
document.body.innerHTML = '<div id="root"></div>';
const root = createRoot(document.getElementById('root')!);
const q = () => within(document.body);
const click = async (name: string) => { await act(async () => { fireEvent.click(q().getByRole('button', { name })); }); };
const set = (key: string, value: unknown) => Object.defineProperty(navigator, key, { configurable: true, value });
let copies: string[] = [], shares: ShareData[] = [];
set('clipboard', { writeText: async (text: string) => { copies.push(text); } });
set('share', async (data: ShareData) => { shares.push(data); });
await act(async () => root.render(<ShareSampleLink id="demo-housing" />));
assert.equal(shares.length, 0); assert.equal(copies.length, 0);
await click('Share link');
assert.equal(shares.length, 1);
assert.deepEqual(shares[0], sampleShareData('demo-housing', 'https://example.test'));
assert.equal(shares[0]!.url, 'https://example.test/votes?proposal=demo-housing');
assert.ok(!JSON.stringify(shares).match(/SECRET|PRIVATE|stance|receipt/));
assert.match(q().getByRole('status').textContent!, /completed.*not verified/);
set('share', async () => { throw new DOMException('Canceled', 'AbortError'); });
await click('Share link'); assert.match(q().getByRole('status').textContent!, /canceled/); assert.equal(copies.length, 0);
set('share', async () => { throw new Error('denied'); });
await click('Share link'); assert.match(q().getByRole('status').textContent!, /Sharing unavailable/);
assert.equal((q().getByRole('textbox') as HTMLInputElement).value, shares[0]!.url);
await click('Copy link'); assert.equal(copies.length, 1); assert.match(q().getByRole('status').textContent!, /Link copied/);
set('share', undefined);
await click('Share link'); assert.equal(copies.length, 2);
set('clipboard', undefined);
await click('Copy link'); assert.match(q().getByRole('status').textContent!, /Could not copy/);
const field = q().getByRole('textbox') as HTMLInputElement;
field.focus(); assert.equal(field.selectionEnd, field.value.length);
set('share', async (data: ShareData) => { shares.push(data); }); set('canShare', () => false);
await click('Share link'); assert.equal(shares.length, 1);
await act(async () => root.render(<ShareSampleLink key="next" id="demo-transit" />));
assert.equal(q().queryByRole('textbox'), null); assert.equal(q().queryByRole('status'), null);
assert.throws(() => sampleShareData('private-journal', 'https://example.test'));
await act(async () => root.unmount()); await dom.happyDOM.close();
console.log('Sample link interactions passed');
