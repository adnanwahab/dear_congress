import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'https://civic.example/proposals/p?evidenceQuestion=What%20is%20the%20cost%3F#evidence' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { within, fireEvent } = await import('@testing-library/dom');
const { CitizenProposalsApp } = await import('../src/client/CitizenProposals');
let writes = 0;
const proposal = { id: 'p', title: 'Night buses', problem: 'No service', proposedChange: 'Add service', jurisdiction: 'city', publishedAt: '2026-11-16', supportingInfo: 'Study https://example.org/study', counts: { support: 0, oppose: 123456, unsure: 0 }, countTotal: 123456, ownVote: 'oppose', comments: [] };
globalThis.fetch = (async (_url: unknown, options?: RequestInit) => {
  if (options?.method && options.method !== 'GET') writes++;
  return Response.json({ proposal });
}) as typeof fetch;
Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('denied'); } } });
document.body.innerHTML = '<div id="root"></div>';
const root = createRoot(document.getElementById('root')!);
await act(async () => { root.render(<CitizenProposalsApp />); await new Promise(resolve => setTimeout(resolve, 100)); });
const q = within(document.body);
assert.equal(document.activeElement?.id, 'evidence');
assert.equal((q.getByLabelText('Which unresolved factual question matters most?') as HTMLTextAreaElement).value, 'What is the cost?');
const click = async (name: string) => { await act(async () => { fireEvent.click(q.getByRole('button', { name })); }); };
await click('Preview question share');
const preview = q.getByLabelText('Share text') as HTMLTextAreaElement;
assert.ok(preview.value.includes('What is the cost?'));
assert.ok(preview.value.includes('Night buses'));
assert.ok(preview.value.includes('https://example.org/study'));
assert.ok(!preview.value.includes('123456') && !preview.value.includes('oppose'));
await click('Copy question share');
assert.ok(document.body.textContent?.includes('Copy unavailable. Select and copy'));
const field = q.getByLabelText('Which unresolved factual question matters most?');
await act(async () => { fireEvent.change(field, { target: { value: '<script>What is the service period?</script>' } }); });
assert.equal(q.queryByLabelText('Share text'), null);
await click('Preview question share');
assert.equal(document.querySelector('script'), null);
assert.equal(writes, 0);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('Evidence question route, focus, preview, escaping, fallback and no-write checks passed');
