import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { ConsensusTerrain, TERRAIN_SCOPE } from '../src/client/ConsensusTerrain';
const dom = new Window({ url: 'http://localhost/votes' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
let requests = 0;
globalThis.fetch = async () => { requests++; throw new Error('Offline'); };
dom.localStorage.setItem('existing-votes', 'unchanged');
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => root.render(<ConsensusTerrain scope={TERRAIN_SCOPE} />));
const select = container.querySelector('select')!;
select.focus();
assert.equal(dom.document.activeElement, select);
assert.match(container.textContent!, /33% support both/);
await act(async () => {
  select.value = 'equal';
  select.dispatchEvent(new dom.Event('change', { bubbles: true }));
});
assert.match(container.textContent!, /13% support both/);
assert.match(container.querySelector('[role="status"]')!.textContent!, /each group contributes half/);
const details = container.querySelector('details')!;
await act(async () => (details.querySelector('summary') as any).click());
assert(details.open);
assert.match(details.textContent!, /Denominator: 20/);
assert.equal(requests, 0);
assert.equal(dom.localStorage.getItem('existing-votes'), 'unchanged');
await act(async () => root.render(<ConsensusTerrain scope="stale" />));
assert.match(container.textContent!, /unavailable/);
assert.equal(container.querySelector('select'), null);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS terrain aggregation, offline rendering, focus, disclosure and stale scope');
