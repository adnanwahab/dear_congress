import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { fireEvent } from '@testing-library/dom';
const dom = new Window({ url: 'http://localhost/classroom' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let requests = 0;
globalThis.fetch = async () => { requests++; throw new Error('Lesson must not fetch'); };
Object.defineProperty(globalThis, 'EventSource', { configurable: true, value: class { constructor() { throw new Error('Lesson must not open live streams'); } } });
for (const storage of [dom.localStorage, dom.sessionStorage]) storage.setItem = () => { throw new Error('Lesson must not save'); };
const { createRoot } = await import('react-dom/client');
const { App } = await import('../src/client/App');
const container = document.createElement('div'); document.body.append(container);
const root = createRoot(container);
await act(async () => { root.render(<App />); });
for (const text of ['Fictional demo.', 'No account, vote or saved ballot', '1 · Compare two alternatives', '2 · Inspect evidence', '3 · Change assumptions', '4 · Discussion questions', '4 / 2', '2 / 4']) assert(container.textContent!.includes(text), text);
assert.equal(container.querySelectorAll('input[type="range"]').length, 3);
const ceiling = container.querySelector('[aria-label="Income eligibility ceiling"]')!;
await act(async () => fireEvent.input(ceiling, { target: { value: '50000' } }));
assert.match(container.textContent!, /4 qualifying; 2 excluded/);
await act(async () => [...container.querySelectorAll('button')].find(b => b.textContent === 'Reset tabletop')!.click());
assert.match(container.textContent!, /2 qualifying; 4 excluded/);
assert.equal(container.querySelector('a[href="/classroom"]')?.getAttribute('href'), '/classroom');
assert.equal(requests, 0);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS classroom isolation, comparison, simulation and reset');
