import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { EvidenceDocket } from '../src/client/EvidenceDocket';
const dom = new Window();
for (const key of ['window', 'document', 'navigator', 'FormData']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const root = createRoot(dom.document.body as any);
await act(async () => root.render(<EvidenceDocket />));
const form = dom.document.querySelector('form')!;
(form.querySelector('[name=evidence]') as any).value = 'Dated source v2, limitations retained';
(form.querySelector('[name=correction]') as any).value = 'Qualify the interpretation';
await act(async () => form.dispatchEvent(new dom.Event('submit', { bubbles: true, cancelable: true })));
assert.match(dom.document.querySelector('[role=status]')!.textContent!, /Nothing was submitted/);
assert.match(dom.document.querySelector('.docket-print')!.textContent!, /Qualify the interpretation/);
const download = [...dom.document.querySelectorAll('button')].find(b => b.textContent === 'Download public docket text')!;
const original = URL.createObjectURL;
URL.createObjectURL = () => { throw new Error('unavailable'); };
await act(async () => download.click());
assert.match(dom.document.querySelector('[role=status]')!.textContent!, /Download unavailable/);
assert.match(dom.document.querySelector('textarea[readonly]')!.textContent!, /Qualify the interpretation/);
URL.createObjectURL = original;
await act(async () => root.unmount());
await dom.happyDOM.abort();
console.log('PASS local draft and failed-download copy fallback');
