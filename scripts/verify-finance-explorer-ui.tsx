import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { fireEvent } from '@testing-library/dom';
const dom = new Window({ url: 'http://localhost/bills?finance=1&q=HFL-051&topic=government' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const { FinanceExplorer } = await import('../src/client/FinanceExplorer');
const { financeExample } = await import('../src/shared/finance-explorer');
const host = document.createElement('div'); document.body.append(host);
const root = createRoot(host);
let requests = 0;
globalThis.fetch = async () => { requests++; throw new Error('Unexpected request'); };
await act(async () => root.render(<FinanceExplorer />));
assert.equal(host.querySelectorAll('article').length, 4);
assert.match(host.textContent!, /external funding 100 = final spending 75/);
assert.match(host.textContent!, /Evidence not checked/);
const search = host.querySelector('input[type=search]') as HTMLInputElement;
search.focus();
await act(async () => fireEvent.input(search, { target: { value: 'city' } }));
assert.equal(document.activeElement, search);
assert.equal(host.querySelectorAll('article').length, 1);
assert.equal(new URLSearchParams(window.location.search).get('q'), 'HFL-051');
const select = host.querySelector('button[aria-pressed]') as HTMLButtonElement;
await act(async () => select.click());
assert.equal(select.getAttribute('aria-pressed'), 'true');
const expand = host.querySelector('button[aria-expanded]') as HTMLButtonElement;
expand.focus();
await act(async () => expand.click());
assert.equal(document.activeElement, expand);
assert.equal(expand.getAttribute('aria-expanded'), 'true');
const saved = window.location.href;
const checkbox = host.querySelector('input[type=checkbox]') as HTMLInputElement;
await act(async () => checkbox.click());
assert.equal(host.querySelector('.finance-track'), null);
assert.equal(select.getAttribute('aria-pressed'), 'true');
assert.equal(expand.getAttribute('aria-expanded'), 'true');
// Simulate native back/forward notifications in DOM; real browser coverage is separate.
for (const url of ['http://localhost/bills?finance=1', saved]) {
  await act(async () => { window.history.replaceState(null, '', url); window.dispatchEvent(new dom.PopStateEvent('popstate')); });
  assert.equal(search.value, url === saved ? 'city' : '');
  assert.equal(host.querySelectorAll('article').length, url === saved ? 1 : 4);
}
await act(async () => fireEvent.input(search, { target: { value: 'missing' } }));
assert.match(host.textContent!, /No agencies match/);
await act(async () => { const dataset = host.querySelector('select')!; fireEvent.change(dataset, { target: { value: 'verified' } }); });
assert.match(host.textContent!, /No compatible accounting dataset/);
assert.doesNotMatch(host.textContent!, /external funding 0/);
await act(async () => { window.history.replaceState(null, '', '/bills?finance=1'); window.dispatchEvent(new dom.PopStateEvent('popstate')); root.render(<FinanceExplorer dataset={{ ...financeExample, checkedAt: '2020-01-01' }} />); });
assert.match(host.textContent!, /Stale or invalid evidence/);
assert.equal(requests, 0);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS finance explorer');
