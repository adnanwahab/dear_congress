/** DOM interaction evidence; native touch, keyboard and layout require browser review. */
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { LocalProjectCheckins } from '../src/client/LocalProjectCheckins';
const dom = new Window({ url: 'http://localhost/map' });
for (const key of ['window', 'document', 'navigator', 'FormData']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => root.render(<LocalProjectCheckins />));
const click = async (prefix: string) => {
  const button = [...container.querySelectorAll('button')].find(b => b.textContent!.startsWith(prefix));
  assert(button, prefix);
  await act(async () => (button as any).click());
};
await click('Explore fictional');
assert(container.textContent!.includes('DEMO ONLY'));
assert(container.textContent!.includes('Prediction made 2026-11-12'));
assert.equal(container.querySelectorAll('svg circle').length, 3);
const history = container.querySelector('article ol')!.textContent;
const form = container.querySelector('form')!;
(form.querySelector('textarea') as any).value = 'Example correction';
(form.querySelector('input') as any).value = 'http://example.org';
await act(async () => { form.dispatchEvent(new dom.Event('submit', { bubbles: true, cancelable: true })); });
assert(container.querySelector('[role=alert]')!.textContent!.includes('HTTPS'));
assert.equal((form.querySelector('textarea') as any).value, 'Example correction');
assert(container.textContent!.includes('(0 pending)'));
(form.querySelector('input') as any).value = 'https://example.org/document';
await act(async () => { form.dispatchEvent(new dom.Event('submit', { bubbles: true, cancelable: true })); });
assert(container.textContent!.includes('(1 pending)'));
assert(container.textContent!.includes('not submitted to a real moderator'));
assert.equal(container.querySelector('article ol')!.textContent, history);
await click('2.');
assert(container.textContent!.includes('Stalled (demo)'));
assert(container.textContent!.includes('Old example observation'));
await click('3.');
assert(container.textContent!.includes('No implementation document or observed update'));
assert(container.textContent!.includes('No forecast available'));
assert(container.textContent!.includes('(1 pending)'));
await click('Hide fictional');
assert(!container.querySelector('form'));
await click('Explore fictional');
assert(container.textContent!.includes('(1 pending)'));
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS local projects: selection, failure, pending queue and immutable evidence');
