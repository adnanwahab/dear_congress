import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import WorkflowScreen from '../src/client/WorkflowScreen';
import { demoPayload } from '../src/engine/demo';
const dom = new Window({ url: 'http://localhost/sponsors?proposal=demo-food' });
for (const key of ['window', 'document', 'navigator', 'localStorage', 'sessionStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
const calls: string[] = [];
const request = async <T,>(path: string): Promise<T> => { calls.push(path); return demoPayload({}, 'test') as T; };
const sentinel = '[{"id":"kept","title":"kept","office":"kept","stage":2,"updatedAt":"kept"}]';
dom.localStorage.setItem('civic_demo_tracker_v1', sentinel);
await act(async () => root.render(<WorkflowScreen stage="sponsors" request={request} />));
const panel = () => container.querySelector('[aria-label="Editable outreach draft"]')!;
const button = (name: string) => [...panel().querySelectorAll('button')].find(b => b.textContent === name)!;
const click = async (name: string) => { await act(async () => (button(name) as any).click()); };
assert(panel()); assert(!button('Download reviewed draft'));
assert(!panel().querySelector('a[href^="mailto:"]'));
let downloaded: Blob | undefined;
const oldCreate = URL.createObjectURL;
URL.createObjectURL = blob => { downloaded = blob as Blob; return 'blob:test'; };
const oldClick = dom.HTMLAnchorElement.prototype.click;
dom.HTMLAnchorElement.prototype.click = function () {};
await click('Review exact draft');
assert(button('Download reviewed draft').disabled);
await act(async () => (panel().querySelector('[type=checkbox]') as any).click());
assert(!button('Download reviewed draft').disabled);
await click('Download reviewed draft');
const text = await downloaded!.text();
assert.match(text, /NOT SENT/); assert.match(text, /demo-food/);
assert.match(text, /Recipient: NOT VERIFIED/); assert(!text.includes('1,080'));
assert.match(panel().textContent!, /no sent or replied status recorded/);
// Any edit invalidates confirmation, including after a successful download.
const input = panel().querySelector('input:not([type=checkbox])')!;
await act(async () => { const setter = Object.getOwnPropertyDescriptor(dom.HTMLInputElement.prototype, 'value')!.set!; setter.call(input, 'Changed subject'); input.dispatchEvent(new dom.Event('input', { bubbles: true })); input.dispatchEvent(new dom.Event('change', { bubbles: true })); });
assert(!button('Download reviewed draft'), 'editing must invalidate review immediately');
assert.equal((panel().querySelector('input') as any).value, 'Changed subject');
await click('Review exact draft');
assert(button('Download reviewed draft').disabled);
const message = panel().querySelector('textarea')!;
await act(async () => { Object.getOwnPropertyDescriptor(dom.HTMLTextAreaElement.prototype, 'value')!.set!.call(message, ''); message.dispatchEvent(new dom.Event('input', { bubbles: true })); });
assert(!button('Download reviewed draft'));
assert(button('Review exact draft').disabled, 'blank messages cannot be reviewed');
await act(async () => { Object.getOwnPropertyDescriptor(dom.HTMLTextAreaElement.prototype, 'value')!.set!.call(message, '<script>private draft</script>'); message.dispatchEvent(new dom.Event('input', { bubbles: true })); });
await click('Review exact draft');
assert(!panel().querySelector('script'), 'drafts render as text');
await click('Cancel review');
assert(!button('Download reviewed draft'));
assert.match(panel().textContent!, /Review cancelled/);
assert.equal(dom.localStorage.getItem('civic_demo_tracker_v1'), sentinel);
assert.deepEqual(calls, ['/api/demo']);
// Context switch remounts and drops the prior draft/review.
const select = container.querySelector('.workflow-select select')!;
await act(async () => { (select as any).value = 'demo-housing'; select.dispatchEvent(new dom.Event('change', { bubbles: true })); });
assert.match(panel().textContent!, /City housing committee/);
assert(!button('Download reviewed draft'));
assert.equal((panel().querySelector('input') as any).value, 'Discussion request: Allow backyard cottages near frequent transit');
await act(async () => root.render(<WorkflowScreen stage="outcomes" request={request} />));
assert.match(container.textContent!, /Draft downloads do not create outreach evidence/);
assert.equal(dom.localStorage.getItem('civic_demo_tracker_v1'), sentinel);
await act(async () => root.unmount());
URL.createObjectURL = oldCreate; dom.HTMLAnchorElement.prototype.click = oldClick;
await dom.happyDOM.close();
console.log('PASS outreach: review, confirmation, cancellation, context isolation, download and evidence boundaries');
