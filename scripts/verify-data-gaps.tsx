import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import WorkflowScreen from '../src/client/WorkflowScreen';
const dom = new Window({ url: 'http://localhost/outcomes' });
for (const key of ['window', 'document', 'navigator', 'localStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const host = dom.document.createElement('div'); dom.document.body.append(host);
const root = createRoot(host as any);
let reject!: (reason: Error) => void;
const request = <T,>() => new Promise<T>((_, fail) => { reject = fail; });
await act(async () => root.render(<WorkflowScreen stage="outcomes" request={request} />));
const atlas = host.querySelector('#data-gaps-atlas')!;
assert(atlas, 'Bundled atlas available while proposals load');
assert.equal(atlas.querySelectorAll('.gap-grid > li').length, 3);
await act(async () => reject(new Error('Offline')));
assert.equal(atlas.querySelectorAll('.gap-grid > li').length, 3);
const topic = atlas.querySelectorAll('select')[1]!;
await act(async () => { topic.value = 'Accessibility'; topic.dispatchEvent(new dom.Event('change', { bubbles: true })); });
assert.match(atlas.querySelector('[role=status]')!.textContent!, /1 of 3/);
assert.match(atlas.querySelector('.gap-grid')!.textContent!, /None registered/);
assert(!atlas.querySelector('.gap-export pre')!.textContent!.includes('acs-travel-definition'));
await act(async () => (atlas.querySelector('button') as any).click());
assert.equal(atlas.querySelectorAll('.gap-grid > li').length, 3);
const download = Array.from(atlas.querySelectorAll('button')).find(b => b.textContent!.includes('Export'))!;
const original = URL.createObjectURL;
URL.createObjectURL = () => { throw new Error('Unavailable'); };
await act(async () => (download as any).click());
assert.match(atlas.querySelector('[role=alert]')!.textContent!, /Download unavailable/);
URL.createObjectURL = original;
const fallback = atlas.querySelector('.gap-export summary')!;
await act(async () => (fallback as any).click());
assert(atlas.querySelector('.gap-export')!.hasAttribute('open'));
assert.match(atlas.querySelector('pre')!.textContent!, /Pending human review/);
await act(async () => root.unmount()); await dom.happyDOM.close();
console.log('PASS loading, offline, filters, reset and failed-download fallback');
