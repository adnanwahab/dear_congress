import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'http://localhost/votes?private=sentinel' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent', 'localStorage', 'sessionStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const events: string[] = [];
globalThis.fetch = (async (url: RequestInfo | URL, init?: RequestInit) => {
  assert.equal(url, '/api/activation-event');
  assert.equal(init?.credentials, 'omit');
  assert.equal(init?.keepalive, true);
  const body = JSON.parse(String(init?.body));
  assert.deepEqual(Object.keys(body), ['event']);
  events.push(body.event);
  return new Response(null, { status: 204 });
}) as typeof fetch;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { ArgumentMap } = await import('../src/client/ArgumentMap');
const { AdvisoryShare } = await import('../src/client/AdvisoryShare');
const { DEMO_ITEMS } = await import('../src/engine/demo');
const { recordActivation } = await import('../src/client/activation-events');
const host = document.createElement('div'); document.body.append(host);
const root = createRoot(host);
await act(async () => root.render(<ArgumentMap item={DEMO_ITEMS.find(i => i.id === 'demo-transit')!} />));
assert.deepEqual(events, []);
const details = host.querySelector<HTMLDetailsElement>('.argument-card details')!;
await act(async () => { details.open = true; });
assert.deepEqual(events, ['argument_opened']);
await act(async () => { details.open = false; });
assert.deepEqual(events, ['argument_opened']);
// No network success is needed for sharing analytics or participation to proceed.
await act(async () => root.render(<AdvisoryShare id="unavailable" />));
await act(async () => host.querySelector<HTMLButtonElement>('button')!.click());
assert.equal(events.at(-1), 'share_opened');
const beforeClose = events.length;
await act(async () => host.querySelector<HTMLButtonElement>('button')!.click());
assert.equal(events.length, beforeClose);
assert.doesNotThrow(() => recordActivation('proposal_read', (() => { throw Error('offline'); }) as typeof fetch));
recordActivation('proposal_read', (() => Promise.reject(Error('offline'))) as typeof fetch);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('Activation browser events verified');
