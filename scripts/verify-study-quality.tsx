import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { StudyQualityMatrix } from '../src/client/StudyQualityMatrix';
const dom = new Window({ url: 'http://localhost/outcomes' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => root.render(<StudyQualityMatrix />));
const buttons = container.querySelectorAll('thead button');
const kind = buttons[1]!;
await act(async () => (kind as any).click());
assert.equal(kind.parentElement!.getAttribute('aria-sort'), 'ascending');
await act(async () => (kind as any).click());
assert.equal(kind.parentElement!.getAttribute('aria-sort'), 'descending');
assert.match(container.querySelector('tbody tr')!.textContent!, /User claim/);
// Native buttons supply keyboard/touch activation; DOM test verifies click dispatch only.
const old = URL.createObjectURL;
URL.createObjectURL = () => { throw new Error('Unavailable'); };
await act(async () => (container.querySelector('.study-controls button') as any).click());
assert.match(container.querySelector('[role=status]')!.textContent!, /Copy the JSON/);
const exported = JSON.parse((container.querySelector('textarea') as any).value);
assert.equal(exported.records.length, 4);
assert.equal(exported.records[0].kind, 'User claim');
URL.createObjectURL = old;
(dom as any).print = () => { throw new Error('Unavailable'); };
await act(async () => (container.querySelectorAll('.study-controls button')[1] as any).click());
assert.match(container.querySelector('[role=status]')!.textContent!, /Printing unavailable/);
await act(async () => root.unmount()); await dom.happyDOM.close();
console.log('PASS sorting and copyable export/print fallback without remote data');
