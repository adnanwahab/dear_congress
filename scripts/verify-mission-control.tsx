import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { OfficialBills } from '../src/client/OfficialBills';
import type { BillObservation } from '../src/shared/legislation';
const dom = new Window({ url: 'http://localhost/outcomes' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
const record = (n: number): BillObservation => ({ id: `congress:119:hr:${n}`, congress: 119, type: 'hr', number: n, title: `Fixture ${n}`, chamber: 'House', sourceUrl: `https://www.congress.gov/bill/119th-congress/house-bill/${n}`, introducedDate: '2026-01-01', sponsors: [], latestAction: { actionDate: '2026-01-02', text: 'Fixture action' }, upstreamUpdatedAt: null, checkedAt: '2026-01-01T00:00:00Z', sourceHash: 'b'.repeat(64), refreshFailed: false });
let mode = 'ok';
const paths: string[] = [];
const request = async <T,>(path: string): Promise<T> => { paths.push(path); if (mode === 'fail') throw Error('offline'); return { bills: mode === 'removed' ? [record(1)] : [record(1), record(2)] } as T; };
const render = async () => { await act(async () => root.render(<OfficialBills request={request} observatory />)); };
await render();
const select = container.querySelector('select')!;
await act(async () => { select.value = record(2).id; select.dispatchEvent(new dom.Event('change', { bubbles: true })); });
assert.equal(container.querySelector('.mission-evidence h4')!.textContent, 'Fixture 2');
// A new request identity triggers a recheck without waiting for the polling interval.
mode = 'fail';
const retryRequest = async <T,>(path: string) => request<T>(path);
await act(async () => root.render(<OfficialBills request={retryRequest} observatory />));
assert.match(container.textContent!, /Refresh failed/);
assert.equal(container.querySelector('.mission-evidence h4')!.textContent, 'Fixture 2');
mode = 'removed';
await act(async () => { const button = container.querySelector('button')!; button.click(); });
assert.match(container.textContent!, /Selected record unavailable/);
assert.equal(container.querySelector('.mission-evidence h4'), null);
assert(paths.every(path => path === '/api/legislation'));
assert.equal(dom.localStorage.length, 0);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS mission control selection, failure, retry and identity isolation');
