import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { NeighborhoodBudget } from '../src/client/NeighborhoodBudget';
const dom = new Window({ url: 'http://localhost/map' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('react-dom/client');
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => root.render(<NeighborhoodBudget />));
const click = async (prefix: string) => {
  const button = [...container.querySelectorAll('button')].find(b => b.textContent!.startsWith(prefix));
  assert(button, prefix);
  await act(async () => button.click());
};
await click('Community hub');
await click('Place Community hub at A1');
await click('Place Community hub at A2');
assert(container.textContent!.includes('insufficient demo credits'));
assert(container.textContent!.includes('40 / 100 credits remaining'));
await click('Use vertical block list');
assert(container.querySelector('.neighborhood-list'));
await click('Remove project at A1');
assert(container.textContent!.includes('100 / 100 credits remaining'));
const drop = new dom.Event('drop', { bubbles: true, cancelable: true });
Object.defineProperty(drop, 'dataTransfer', { value: { getData: () => 'play' } });
await act(async () => { container.querySelector('.neighborhood-block')!.dispatchEvent(drop); });
assert(container.textContent!.includes('60 / 100 credits remaining'));
await click('Clear neighborhood demo');
assert(container.textContent!.includes('0 / 9 blocks covered'));
await act(async () => root.unmount());
await dom.happyDOM.close();
