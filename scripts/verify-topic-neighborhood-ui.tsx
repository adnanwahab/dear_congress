import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { fireEvent } from '@testing-library/dom';
const dom = new Window({ url: 'http://localhost/topics/housing?q=Housing' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let motionListener: (() => void) | undefined;
let reduced = false;
Object.defineProperty(window, 'matchMedia', { value: () => ({ get matches() { return reduced; }, addEventListener: (_: string, f: () => void) => motionListener = f, removeEventListener: () => {} }) });
const { createRoot } = await import('react-dom/client');
const { TopicNeighborhood } = await import('../src/client/TopicNeighborhood');
const hub = { topic: { id: 'housing', label: 'Housing', color: '#1e40af', icon: '' }, needs: [{ id: 'housing', label: 'Housing affordability', goal: 'Affordable homes', metric: 'Rent' }], proposals: [{ id: 'p', needId: 'housing', title: 'Sample policy', jurisdiction: 'city' }], stories: [{ id: 'sample', text: 'DO NOT DISPLAY PRIVATE PROSE', needIds: ['housing'], proposalIds: ['p'] }] } as any;
const container = document.createElement('div'); document.body.append(container);
const root = createRoot(container);
let requests = 0;
globalThis.fetch = async () => { requests++; throw new Error('No network expected'); };
await act(async () => root.render(<TopicNeighborhood hub={hub} />));
assert(container.querySelector('svg.neighborhood-map'));
assert(!container.textContent!.includes('DO NOT DISPLAY'));
const button = (text: string) => [...container.querySelectorAll('button')].find(b => b.textContent === text)!;
await act(async () => button('need: Housing affordability').click());
assert.equal(document.activeElement?.getAttribute('aria-label'), 'Selected neighborhood record');
assert.equal(new URLSearchParams(window.location.search).get('q'), 'Housing');
assert.equal(new URLSearchParams(window.location.search).get('node'), 'need:housing');
assert(container.querySelector('[aria-label="Selected neighborhood record"]')!.textContent!.includes('Sample policy'));
const selectedUrl = window.location.href;
await act(async () => button('Static / low-power list').click());
assert(!container.querySelector('svg.neighborhood-map'));
assert(container.querySelector('[aria-label="Selected neighborhood record"]')!.textContent!.includes('Affordable homes'));
const listUrl = window.location.href;
// Exercise actual history traversal, including selection and mode restoration.
await act(async () => {
  const restored = new Promise<void>(resolve => window.addEventListener('popstate', () => resolve(), { once: true }));
  window.history.back(); await restored;
});
assert.equal(window.location.href, selectedUrl);
assert(container.querySelector('svg.neighborhood-map'));
await act(async () => {
  const restored = new Promise<void>(resolve => window.addEventListener('popstate', () => resolve(), { once: true }));
  window.history.forward(); await restored;
});
assert.equal(window.location.href, listUrl);
assert(!container.querySelector('svg.neighborhood-map'));
const search = container.querySelector('input[type=search]')!;
(search as HTMLInputElement).focus();
await act(async () => fireEvent.input(search, { target: { value: 'missing' } }));
assert(container.textContent!.includes('No records match'));
assert.equal(document.activeElement, search);
await act(async () => { window.history.replaceState(null, '', selectedUrl); window.dispatchEvent(new dom.PopStateEvent('popstate')); reduced = true; motionListener?.(); });
assert(!container.querySelector('svg.neighborhood-map'));
assert(button('Show map').disabled);
assert(container.textContent!.includes('Reduced motion'));
await act(async () => root.render(<TopicNeighborhood hub={{ ...hub, needs: [], proposals: [], stories: [] }} />));
assert(container.textContent!.includes('No records match'));
assert(container.textContent!.includes('Selected record unavailable'));
assert.equal(requests, 0);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS neighborhood UI');
