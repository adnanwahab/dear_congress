import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { SourceHealth } from '../src/client/SourceHealth';
const dom = new Window({ url: 'http://localhost/outcomes' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let respond: (response: Response) => void = () => {};
globalThis.fetch = (() => new Promise<Response>(resolve => { respond = resolve; })) as typeof fetch;
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => { root.render(<SourceHealth />); });
assert.match(container.textContent!, /Loading source records/);
await act(async () => { respond(Response.json({ outcomes: null })); });
assert.match(container.textContent!, /No source snapshot/);
assert.equal(container.querySelectorAll('h3').length, 3);
const buttons = container.querySelectorAll('button');
assert.equal(buttons[1]!.getAttribute('type'), 'button');
await act(async () => { buttons[1]!.dispatchEvent(new dom.MouseEvent('click', { bubbles: true })); });
assert.match(container.querySelector('pre')!.textContent!, /source-health-v1/);
assert.match(container.querySelector('pre')!.textContent!, /not verified measurements/);
globalThis.fetch = (async () => { throw new Error('offline'); }) as typeof fetch;
await act(async () => { buttons[0]!.dispatchEvent(new dom.MouseEvent('click', { bubbles: true })); });
assert.match(container.textContent!, /unavailable or offline/);
assert.match(container.textContent!, /No replacement measurements/);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS loading, missing, offline, retry and copy/print fallback');
