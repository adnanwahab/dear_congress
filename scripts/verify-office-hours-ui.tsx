import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'http://localhost/draft' });
for (const key of ['window','document','navigator','HTMLElement','HTMLInputElement','HTMLTextAreaElement','Element','Node','Event','MouseEvent','MutationObserver','localStorage','sessionStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let requests = 0;
globalThis.fetch = (async () => { requests++; throw new Error('Network forbidden'); }) as any;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { within, fireEvent } = await import('@testing-library/dom');
const { OfficeHours } = await import('../src/client/OfficeHours');
const root = createRoot(document.body.appendChild(document.createElement('div')));
const q = () => within(document.body);
const click = async (name: string | RegExp) => act(async () => { fireEvent.click(q().getByRole('button', { name })); });
const edit = async (label: string | RegExp, value: string) => act(async () => { fireEvent.change(q().getByLabelText(label), { target: { value } }); });
const source = { repository: 'adnanwahab/dear_congress' as const, kind: 'sample' as const, id: 'a', revision: 'v1' };
try {
  await act(async () => { root.render(<OfficeHours source={source} />); });
  await edit('Question about this draft', '<script>Question?</script>');
  assert((q().getByRole('button', { name: 'Add to rehearsal queue' }) as HTMLButtonElement).disabled);
  await act(async () => { fireEvent.click(q().getByRole('checkbox')); });
  await click('Add to rehearsal queue');
  assert(q().getByText('Question 1 · pending'));
  await edit('Moderation reason', 'Relevant to this draft'); await click('Approve question locally');
  await edit('Expert opinion', 'Compare a baseline.');
  await edit(/Source evidence note \(title/, 'javascript:alert(1) — no evidence supplied');
  await click('Record answer locally');
  await edit('Expert opinion', 'Use a comparison group too.');
  await edit(/Source evidence note \(title/, 'No evidence supplied');
  await edit('Correction or withdrawal reason', 'Missing caveat'); await click('Record correction locally');
  assert(q().getByText('Timestamped answer history (2)'));
  await edit('Correction or withdrawal reason', 'Outside scope'); await click('Withdraw answer locally');
  assert(q().getByText('Answer withdrawn. Do not rely on earlier versions.'));
  assert(q().getByText('Timestamped answer history (3)'));
  assert.equal(document.querySelectorAll('script, a[href^="javascript:"]').length, 0);
  // A missed caller remount fails closed and retains editing text on failure.
  await act(async () => { root.render(<OfficeHours source={{ ...source, revision: 'v2' }} />); });
  await edit('Question about this draft', 'Keep this unsaved text');
  await act(async () => { fireEvent.click(q().getByRole('checkbox')); }); await click('Add to rehearsal queue');
  assert(q().getByRole('alert').textContent?.includes('revision changed'));
  assert.equal((q().getByLabelText('Question about this draft') as HTMLTextAreaElement).value, 'Keep this unsaved text');
  await act(async () => { root.render(<OfficeHours key="sample:b:v1" source={{ ...source, id: 'b' }} />); });
  assert(q().getByText('No questions yet. Add a question to try moderation.'));
  assert.equal(requests, 0);
  // Verify real workflow composition and loading/failure boundaries.
  const { default: WorkflowScreen } = await import('../src/client/WorkflowScreen');
  const { DEMO_ITEMS } = await import('../src/engine/demo');
  let finish!: (value: any) => void;
  const delayed = new Promise(resolve => { finish = resolve; });
  await act(async () => { root.render(<WorkflowScreen key="loading" stage="draft" request={async <T,>() => await delayed as T} />); });
  assert.equal(q().queryByText('Expert office hours · local rehearsal'), null);
  await act(async () => { finish({ items: DEMO_ITEMS, votes: {}, updatedAt: '2026-11-14', closesAt: '2026-11-15' }); });
  assert(q().getByText('Expert office hours · local rehearsal'));
  await act(async () => { root.render(<WorkflowScreen stage="draft" request={async <T,>() => ({ items: DEMO_ITEMS, votes: {}, updatedAt: '2026-11-14', closesAt: '2026-11-15' }) as T} />); });
  assert(q().getByText('Expert office hours · local rehearsal'));
  await act(async () => { root.render(<WorkflowScreen key="failed" stage="draft" request={async () => { throw new Error('offline'); }} />); });
  assert.equal(q().queryByText('Expert office hours · local rehearsal'), null);
  assert(q().getByRole('button', { name: 'Retry loading proposals' }));
  console.log('PASS office hours moderation, correction, withdrawal, source isolation, failure text retention, escaped citations, no network and workflow integration');
} finally { await act(async () => root.unmount()); await dom.happyDOM.close(); }
