import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { getByLabelText, getByRole } from '@testing-library/dom';
import { ProposalObjections } from '../src/client/ProposalObjections';
import { citizenProposalView, publishCitizenProposal, objectCitizenProposal, type CitizenProposalStore } from '../src/server/citizen-proposals';
const dom = new Window({ url: 'http://localhost/proposals/test' });
for (const key of ['window', 'document', 'navigator', 'FormData']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const db: CitizenProposalStore = { entries: [] };
const { record } = publishCitizenProposal(db, 'publishing-browser', { title: 'Access', problem: 'Steps', proposedChange: 'Ramp', jurisdiction: 'city', confirmedPublic: true, idempotencyKey: crypto.randomUUID() });
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
let fail = true;
const keys: string[] = [];
function render() {
  root.render(<ProposalObjections proposal={citizenProposalView(record, 'publishing-browser')} submit={async (value: any) => {
    keys.push(value.idempotencyKey);
    if (fail) throw Error('Offline; retry');
    objectCitizenProposal(db, record.id, 'publishing-browser', value);
    render();
  }} />);
}
await act(async () => render());
const field = (label: string) => getByLabelText(container as any, label) as any;
field('Objection').value = '<script>unsafe()</script>';
field('Impacted constituency (self-described)').value = 'Wheelchair users';
field('Severity').value = 'blocking';
field('I consent to publish this objection and constituency description publicly.').checked = true;
const publish = getByRole(container as any, 'button', { name: 'Publish objection' }) as any;
await act(async () => publish.click());
assert.match(getByRole(container as any, 'alert').textContent!, /Offline/);
assert.equal(field('Objection').value, '<script>unsafe()</script>');
fail = false;
await act(async () => publish.click());
assert.equal(keys[0], keys[1]);
assert.equal(record.objections!.length, 1);
assert.equal(container.querySelectorAll('script').length, 0);
assert.match(container.textContent!, /blocking · unresolved/);
field('Decision').value = 'declined';
field('Reason').value = 'Outside this pilot';
await act(async () => (getByRole(container as any, 'button', { name: 'Save proposer response' }) as any).click());
assert.match(container.textContent!, /blocking · declined/);
assert.match(container.textContent!, /Outside this pilot/);
assert.equal(record.objections![0]!.responses.length, 1);
assert.equal(record.proposedChange, 'Ramp');
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('PASS objection form labels, consent, retry, safe text and proposer response');
