import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { ResponsibilityExplorer } from '../src/client/ResponsibilityExplorer';
const dom = new Window({ url: 'http://localhost/feed' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => { root.render(<ResponsibilityExplorer loading />); });
assert.match(container.textContent!, /Loading proposal context/);
assert.equal(container.querySelector('section')!.getAttribute('aria-busy'), 'true');
await act(async () => { root.render(<ResponsibilityExplorer failed />); });
assert.match(container.textContent!, /Proposal context unavailable/);
assert.equal(container.querySelectorAll('li a').length, 4);
const select = container.querySelector('select')!;
await act(async () => { select.value = 'texas'; select.dispatchEvent(new dom.Event('change', { bubbles: true })); });
assert.match(container.querySelector('ol')!.textContent!, /Texas House and Senate/);
assert.match(container.textContent!, /No city, county or transit-board authority is established/);
await act(async () => { (container.querySelector('input') as any).click(); });
assert(container.querySelector('.responsibility-outline'));
assert.equal(container.querySelectorAll('details[open]').length, 4);
const sources = [...container.querySelectorAll('li a')].map(a => a.getAttribute('href'));
await act(async () => { (container.querySelector('input') as any).click(); });
assert.deepEqual([...container.querySelectorAll('li a')].map(a => a.getAttribute('href')), sources);
await act(async () => { root.render(<ResponsibilityExplorer proposal={{ title: 'Different revision', jurisdiction: 'County' }} />); });
assert.match(container.textContent!, /Different revision/);
assert.match(container.textContent!, /Office assignment remains unverified/);
await act(async () => root.unmount());
console.log('PASS responsibility navigation, outline, loading, failure and revision context');
