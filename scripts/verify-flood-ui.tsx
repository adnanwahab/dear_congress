import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { getByRole } from '@testing-library/dom';
import { FloodLogistics } from '../src/client/FloodLogistics';
const dom = new Window({ url: 'http://localhost/bills' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let writes = 0;
(globalThis as any).fetch = () => { writes++; throw Error('Game must not use network'); };
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => root.render(<FloodLogistics />));
const button = (name: string) => getByRole(container as any, 'button', { name, exact: true }) as HTMLButtonElement;
const click = async (name: string) => act(async () => button(name).click());
await click('Start fictional exercise');
for (let round = 0; round < 3; round++) {
  await click('Place crew at Willow homes');
  assert.equal(button('Place crew at Orchard workshop').disabled, true);
  const select = container.querySelector('select')!;
  await act(async () => { select.value = 'kit'; select.dispatchEvent(new dom.Event('change', { bubbles: true })); });
  await click('Place drainage kit at Orchard workshop');
  await act(async () => { select.value = 'closure'; select.dispatchEvent(new dom.Event('change', { bubbles: true })); });
  await click('Place road closure at Lantern square');
  assert.match(container.textContent!, /Time: 0 hours remaining/);
  await click('Run hypothetical round');
  if (round < 2) await act(async () => { select.value = 'crew'; select.dispatchEvent(new dom.Event('change', { bubbles: true })); });
}
assert.match(container.textContent!, /Fictional exercise complete/);
assert.equal(container.querySelectorAll('li').length, 3);
assert.match(container.textContent!, /Willow homes: 4 remaining disruption units/);
await click('Restart exercise');
assert.equal(container.querySelectorAll('li').length, 0);
await click('Skip round');
assert.match(container.textContent!, /skipped; no resources placed/);
await click('Exit exercise');
assert.ok(button('Start fictional exercise'));
assert.equal(writes, 0);
assert.equal(dom.localStorage.length, 0);
assert.equal(dom.sessionStorage.length, 0);
await act(async () => root.unmount()); await dom.happyDOM.close();
console.log('PASS flood resource limits, three rounds, reset, skip, exit and isolation');
