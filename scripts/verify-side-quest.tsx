import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const dom = new Window({ url: 'http://localhost/' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent', 'localStorage']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { within, fireEvent } = await import('@testing-library/dom');
const { SideQuest, SIDE_QUESTS } = await import('../src/client/SideQuest');
let root = createRoot(document.body.appendChild(document.createElement('div')));
const q = () => within(document.body);
const show = async (props: Parameters<typeof SideQuest>[0]) => act(async () => root.render(<SideQuest {...props} />));
const click = async (name: string) => act(async () => fireEvent.click(q().getByRole('button', { name })));
const remount = async () => { await act(async () => root.unmount()); root = createRoot(document.body.appendChild(document.createElement('div'))); };
await show({ loading: true });
assert.match(q().getByRole('status').textContent!, /Loading/);
assert.equal(q().queryAllByRole('link').length, 0);
await show({ item: { id: 'demo-food' }, failed: true });
assert.match(q().getByRole('status').textContent!, /unavailable/);
assert.equal(q().queryAllByRole('link').length, 0);
await show({});
assert.match(document.body.textContent!, /No reviewed related reading/);
await show({ item: { id: 'unknown' } });
assert.equal(q().queryAllByRole('link').length, 0);
for (const id of Object.keys(SIDE_QUESTS)) {
  await show({ item: { id } });
  assert.equal(q().getAllByRole('link').length, 1);
  const link = q().getByRole('link');
  assert.equal(link.getAttribute('href'), SIDE_QUESTS[id]!.url);
  assert.equal(link.getAttribute('referrerpolicy'), 'no-referrer');
  assert.match(document.body.textContent!, /Why this suggestion/);
  assert.match(document.body.textContent!, /fictional/);
}
await show({ item: { id: 'demo-food' } });
q().getByRole('link').focus();
assert.equal(document.activeElement, q().getByRole('link'));
await click('Dismiss this suggestion');
assert.equal(document.activeElement, q().getByRole('heading', { name: 'One optional detour' }));
assert.equal(q().queryAllByRole('link').length, 0);
await remount(); await show({ item: { id: 'demo-food' } });
assert.match(document.body.textContent!, /No replacement/);
await show({ item: { id: 'demo-housing' } });
assert.equal(q().getAllByRole('link').length, 1);
await click('Turn off related reading');
await remount(); await show({ item: { id: 'demo-health' } });
assert.equal(q().queryAllByRole('link').length, 0);
await click('Turn related reading on');
assert.equal(q().getAllByRole('link').length, 1);
Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } } });
await click('Turn off related reading');
assert.match(document.body.textContent!, /lasts only while this page is open/);
await remount(); await show({ item: { id: 'demo-health' } });
assert.equal(q().getAllByRole('link').length, 1);
await act(async () => root.unmount());
await dom.happyDOM.close();
console.log('Side quest: source scope, states, dismissal, off/on, focus and blocked storage passed');
