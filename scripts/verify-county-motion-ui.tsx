/** Deterministic DOM lifecycle checks; native painting/performance needs browser QA. */
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { act } from 'react';
import MapScreen from '../src/client/MapScreen';
const dom = new Window({ url: 'http://localhost/map' });
for (const key of ['window', 'document', 'navigator']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let reduced = false;
const listeners = new Set<() => void>();
Object.defineProperty(dom, 'matchMedia', { value: () => ({ get matches() { return reduced; }, addEventListener(_: string, cb: () => void) { listeners.add(cb); }, removeEventListener(_: string, cb: () => void) { listeners.delete(cb); } }) });
let next = 0;
const frames = new Map<number, FrameRequestCallback>();
dom.requestAnimationFrame = cb => { frames.set(++next, cb); return next; };
dom.cancelAnimationFrame = id => { frames.delete(id); };
const frame = async (time: number) => { await act(async () => { const pending = [...frames.values()]; frames.clear(); pending.forEach(cb => cb(time)); }); };
const { createRoot } = await import('react-dom/client');
const container = dom.document.createElement('div');
dom.document.body.append(container);
const root = createRoot(container as any);
await act(async () => { root.render(<MapScreen />); });
const click = async (label: string) => { await act(async () => { const b = [...container.querySelectorAll('button')].find(b => b.textContent === label)!; assert(b && !(b as any).disabled); (b as any).click(); }); };
const metrics = () => [...container.querySelectorAll('.county-metrics strong')].map(n => n.textContent);
await click('Improve one revision');
assert.equal(metrics()[3], '01');
await frame(0); await frame(600);
assert.equal(metrics()[3], '02');
await frame(1200);
const paths = [...container.querySelectorAll('.county-shape')];
assert.equal(paths.length, 3144);
assert(new Set(paths.map(p => (p as any).style.transitionDelay)).size > 100);
const revision = () => Number(container.querySelector('.county-plan-title')!.textContent!.split('v').pop());
while (!container.querySelector('.county-completion-sweep')) {
  assert(revision() < 12);
  await click('Improve one revision');
}
const sweep = container.querySelector('.county-completion-sweep');
assert(container.querySelector('[role=status]')!.textContent!.startsWith('Simulation complete.'));
assert(container.querySelector('.county-live')!.textContent!.includes('Simulation complete'));
// The count advances between endpoints; only the small metrics subtree changes per frame.
await frame(2000); const before = metrics(); await frame(2300); const during = metrics();
assert.notEqual(during[1], before[1]);
assert.notEqual(during[1], '3,144 / 3,144');
assert.equal(container.querySelector('.county-shape'), paths[0]);
await frame(3200);
assert.equal(metrics()[1], '3,144 / 3,144');
await click('+');
assert.equal(container.querySelector('.county-completion-sweep'), sweep);
await click('Restart');
assert.equal(container.querySelector('.county-completion-sweep'), null);
assert.equal(metrics()[3], '01');
reduced = true;
await act(async () => { listeners.forEach(cb => cb()); });
while (!container.querySelector('.county-completion-sweep')) await click('Improve one revision');
assert.equal(metrics()[1], '3,144 / 3,144');
assert.equal(frames.size, 0);
assert.notEqual(container.querySelector('.county-completion-sweep'), sweep);
await act(async () => { root.unmount(); });
assert.equal(frames.size, 0);
await dom.happyDOM.close();
console.log('PASS county motion: ripple delays, counters, completion lifecycle, restart and reduced motion');
