const {act}=await import('react');
const {createRoot}=await import('react-dom/client');
const {fireEvent,within}=await import('@testing-library/dom');
const {PatchCarousel}=await import('../src/client/PatchCarousel');
const pulls:PublicPull[]=['blocked','waiting-for-checks','approved'].map((state,i)=>({kind:'pr',number:i+1,repositoryId:9,title:['Blocked patch','Pending patch','Review-ready patch'][i]!,body:'Description',author:'fixture',url:'',updatedAt:'',headSha:`sha${i}`,base:'main',version:`v${i}`,draft:false,state:'open',firstSeenAt:0,labels:[],tally:{yes:0,no:0,participation:0,feedback:0},eligibility:{eligible:false,state:state as PublicPull['eligibility']['state'],reason:`Reason ${state}`},evidence:{checks:[{name:'CI',status:i===1?'in_progress':'completed',conclusion:i===1?null:'success',sha:`sha${i}`}],reviews:[],requestedReviewers:0,mergeable:true,mergeableState:'clean',baseSha:'base',protectionsKnown:true,protectedBase:true,sensitive:false,maintainerApproved:false}}));
const list={repository:'adnanwahab/dear_congress',pulls,viewer:{authenticated:false,approved:false},sourceStatus:'github',stale:false,lastSync:null} as PullList;
const calls:string[]=[];
globalThis.fetch=(async (url,init)=>{assert.equal(init?.method,undefined);calls.push(String(url));return new Response(JSON.stringify({pull:pulls[Number(String(url).split('/').pop())-1],viewer:list.viewer}));}) as typeof fetch;
