import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { fixture, selection } from './fixtures';
import type { Submission, WorkbenchAdapter } from './contract';
const dom = new Window({ url: 'http://localhost' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'HTMLInputElement', 'HTMLTextAreaElement', 'Event']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? dom : (dom as any)[key] });
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { getByLabelText, getByRole, fireEvent } = await import('@testing-library/dom');
const { HeliosWorkbench } = await import('./HeliosWorkbench');
const container = dom.document.createElement('div'); dom.document.body.append(container);
const root = createRoot(container as any);
let data = await fixture(); let fail = true;
const submissions: Submission[] = [];
const adapter: WorkbenchAdapter = { load: async () => data, submit: async value => { submissions.push(value); if (fail) throw Error('PRIVATE ERROR DETAILS'); return { receipt: 'durable-receipt' }; } };
async function flush() { await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); }); }
await act(async () => root.render(<HeliosWorkbench selection={selection} adapter={adapter} />)); await flush();
assert.match(container.textContent!, /Full source <script>/);
assert.equal(container.querySelectorAll('script,img').length, 0);
assert.ok(!container.textContent!.includes('PRIVATE SECRET'));
assert.match(container.textContent!, /Pending legal review/);
const field = (label: string) => getByLabelText(container as any, label) as any;
const publish = () => getByRole(container as any, 'button', { name: 'Publish objection' }) as any;
assert.equal(publish().disabled, true);
await act(async () => {
  fireEvent.input(field('Objection text'), { target: { value: 'My public objection' } });
  field('I consent to publishing this objection for this exact revision.').click();
});
assert.equal(publish().disabled, false);
await act(async () => publish().click());
assert.match(container.textContent!, /Could not confirm save/);
assert.ok(!container.textContent!.includes('PRIVATE ERROR DETAILS'));
assert.equal(field('Objection text').value, 'My public objection');
assert.equal(dom.document.activeElement?.getAttribute('role'), 'status');
fail = false;
await act(async () => publish().click()); await flush();
assert.equal(submissions[0]!.requestId, submissions[1]!.requestId);
assert.equal(submissions[1]!.revision, selection.revision);
assert.match(container.textContent!, /durable-receipt/);
await act(async () => {
  fireEvent.change(field('Version to respond to'), { target: { value: 'amendment-1' } });
  fireEvent.change(field('Advisory response'), { target: { value: 'unsure' } });
  field('I reviewed this version and consent to a fresh advisory response.').click();
});
await act(async () => (getByRole(container as any, 'button', { name: 'Save response' }) as any).click()); await flush();
assert.equal(submissions[2]!.revision, 'catalog-r2');
assert.equal((submissions[2] as any).roundId, 'round-2');
assert.equal(data.round!.support, 0); // no optimistic/transferred counts
const next = { ...selection, revision: 'new-revision' };
data = { ...data, source: { ...data.source, ...next }, amendments: [] };
await act(async () => root.render(<HeliosWorkbench selection={next} adapter={adapter} />)); await flush();
assert.equal(field('Objection text').value, ''); assert.equal(publish().disabled, true);
assert.ok(!container.textContent!.includes('durable-receipt'));
data.source.textHash = 'mismatch';
await act(async () => root.render(<HeliosWorkbench selection={{ ...next, revision: 'bad' }} adapter={adapter} />)); await flush();
assert.match(getByRole(container as any, 'alert').textContent!, /blocked/);
assert.equal(container.querySelector('textarea'), null);
await act(async () => root.unmount()); await dom.happyDOM.close();
console.log('PASS workbench walkthrough');
